#!/usr/bin/env python3
"""Optional fixture regeneration; PyTorch is needed here, never by native CI.
Reads the tracked native artifact, then evaluates export_strategic_tok.NpForward.
"""
import hashlib
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import numpy as np
import torch
from strategic_tok_net import Net
from export_strategic_tok import DIMS, W_ORDER, NpForward

artifact = Path('selfplay/models/ooc_strategic_tok_final.native')
data = artifact.read_bytes()
assert data[:12] == b'OOC_STRAT_V4'
assert np.frombuffer(data, '<i4', 17, 12).tolist() == DIMS
pos = 80
mean = np.frombuffer(data, '<f4', 42, pos).copy(); pos += 168
inv = np.frombuffer(data, '<f4', 42, pos).copy(); pos += 168
sd = Net().state_dict()
order = W_ORDER + [f'vals.{h}.{suffix}' for suffix in ['0.weight','0.bias','2.weight','2.bias'] for h in range(8)] + ['q.0.weight','q.0.bias','q.2.weight','q.2.bias']
for key in order:
    n = sd[key].numel()
    sd[key] = torch.from_numpy(np.frombuffer(data, '<f4', n, pos).copy().reshape(tuple(sd[key].shape)))
    pos += n*4
assert pos == len(data)
ref = NpForward({'state_dict':sd,'mean':mean,'inv':inv})
glob = np.array([(i-20)*0.125 for i in range(42)], np.float32)
dk = [(1,0,5),(42,1,2),(100,0,1)]
rl = [(1,1),(23,4)]
pt = [(2,1),(7,2)]
rows = []
for i in range(4):
    bits = [0, 65536, 0x12345678, 0xFFFFFFFF][i]
    cats = [i,2,0,42,-1,3]
    et = i; ei = [-1,42,23,7][i]
    logit, _, q = ref.fwd(glob,dk,rl,pt,bits,cats,i-1,i+1,et,ei,float(i%2))
    rows.append(f'    {{{bits}u, {{{", ".join(map(str,cats))}}}, {i-1}, {i+1}, {et}, {ei}, {i%2}.0f, {logit:.12g}, {q:.12g}}}')
header = '// Generated by tools/verify/generate_ooc_v4_policy_fixture.py\n// NpForward.fwd; artifact SHA256 '+hashlib.sha256(data).hexdigest()+'\n'
header += 'struct V4PolicyFixture { std::uint32_t bits; int cats[6]; int type, screen, entityType, entityId; float price; double logit, q; };\n'
header += 'static const V4PolicyFixture v4PolicyFixtures[] = {\n'+',\n'.join(rows)+'\n};\n'
Path('tests/data/ooc_v4_policy_fixture.h').write_text(header)
print(header)
