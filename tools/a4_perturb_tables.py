#!/usr/bin/env python3
"""Writes apps/one_combat/a4_perturb_tables.inc: how often each card (id, upgraded), relic id and potion appears in real
Act-4 entry states, for the STS_A4_PERTURB card-, relic- and potion-add operators (a4_perturb.cpp filters the rows).

  python3 -I tools/a4_perturb_tables.py STATES_A4.pkl MORE_A4.pkl OUT.inc

Inputs are the V_A4 entry pickles (/mnt/project-files/value-a4-improve/, 2026-10-30): heart1-public-record-v2
records at the first Act-4 state of each game. Entries whose public state repeats (forks of one entry) count once.
"""
import collections, hashlib, json, pickle, sys


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def main(states_path, more_path, out_path):
    with open(states_path, "rb") as f:
        states = pickle.load(f)
    with open(more_path, "rb") as f:
        more = pickle.load(f)
    records = [g["states"][0]["record"] for g in states] + [g["entry"]["record"] for g in more if g.get("entry")]
    if any(r["obs.act"] != 4 for r in records):
        raise SystemExit("a record is not in act 4")
    seen, unique = set(), []
    for r in records:
        key = json.dumps([r[k] for k in ("obs.fixed_observation", "obs.deck.cards", "obs.deck.upgrades",
                                         "obs.relics.relics", "obs.potions")])
        if key not in seen:
            seen.add(key)
            unique.append(r)
    cards, relics, potions = collections.Counter(), collections.Counter(), collections.Counter()
    for r in unique:
        for card, upgrades in zip(r["obs.deck.cards"], r["obs.deck.upgrades"]):
            cards[(card, min(upgrades, 1))] += 1
        relics.update(r["obs.relics.relics"])
        potions.update(r["obs.potions"])
    lines = ["// Generated by tools/a4_perturb_tables.py; do not edit.",
             f"// {len(unique)} distinct Act-4 entry states of {len(records)} records.",
             f"// {states_path.rsplit('/', 1)[-1]} sha256 {sha256(states_path)}",
             f"// {more_path.rsplit('/', 1)[-1]} sha256 {sha256(more_path)}",
             f"constexpr int kA4EntryStates = {len(unique)};",
             "// {CardId, upgraded, count}",
             "constexpr A4CardCount kA4Cards[] = {"]
    lines += [f"    {{{c}, {u}, {n}}}," for (c, u), n in sorted(cards.items())]
    lines += ["};", "// {RelicId, count}", "constexpr A4RelicCount kA4Relics[] = {"]
    lines += [f"    {{{r}, {n}}}," for r, n in sorted(relics.items())]
    lines += ["};", "// {Potion, count} (slots, so EMPTY_POTION_SLOT too)", "constexpr A4PotionCount kA4Potions[] = {"]
    lines += [f"    {{{p}, {n}}}," for p, n in sorted(potions.items())]
    lines += ["};"]
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
