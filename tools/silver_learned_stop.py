#!/usr/bin/env python3
"""Learned native-Silver stopping: train, evaluate offline, export to C++.

Input is the CSV written by `STS_SILVER_STOP_TRACE` during exact-10k play:
one row per (root decision, checkpoint) with the feature vector of
include/sim/search/NativeSilverStopModel.h and the checkpoint leader. The
label of a row is "leader differs from the 10k leader of the same decision".

  silver_learned_stop.py placeholder --cpp OUT
      write the untrained model (runtime refuses to use it)
  silver_learned_stop.py train TRACE... --train-seeds LO:HI --out-dir DIR
      fit on decisions whose run seed is in [LO, HI], write model.json,
      NativeSilverStopModel.cpp and offline.json
  silver_learned_stop.py selftest

Requires scikit-learn for `train` only.
"""
import argparse
import csv
import gzip
import hashlib
import json
import math
import sys
from pathlib import Path

FEATURES = [
    "checkpoint", "inherited_visits", "fresh_root", "legal_actions", "top_share",
    "second_share", "gap_share", "entropy", "q_gap", "q_gap_valid", "root_visits",
    "turn", "act", "room", "leader_same", "leader_streak", "rho", "lock",
]
CHECKPOINTS = [250, 500, 1000, 2000, 4000, 8000, 10000]
BMAX = 10000
TOP_GAP_199 = 0.2932885906040268

HEADER = """// Generated by tools/silver_learned_stop.py; do not edit.
#include "sim/search/NativeSilverStopModel.h"

#include <cmath>

namespace sts::search {

namespace {
"""

FOOTER = """
}

bool nativeSilverStopModelTrained() { return kTrained; }
const char *nativeSilverStopModelId() { return kModelId; }
double nativeSilverStopModelDefaultThreshold() { return kDefaultThreshold; }

double nativeSilverStopModelRisk(const NativeSilverStopFeatures &x) {
    if (!kTrained) return 1.0;
    double raw = kBaseline;
    for (int t = 0; t < kTreeCount; ++t) {
        int n = kTreeRoots[t];
        while (!kNodes[n].leaf) {
            n = x[kNodes[n].feature] <= kNodes[n].threshold ? kNodes[n].left : kNodes[n].right;
        }
        raw += kNodes[n].value;
    }
    return 1.0 / (1.0 + std::exp(-raw));
}

}
"""


def write_cpp(path, model):
    nodes, roots = [], []
    for tree in model["trees"]:
        roots.append(len(nodes))
        base = len(nodes)
        for n in tree:
            nodes.append(dict(n, left=n["left"] + base if not n["leaf"] else 0,
                              right=n["right"] + base if not n["leaf"] else 0))
    if not nodes:
        nodes.append({"leaf": True, "feature": 0, "threshold": 0.0, "left": 0, "right": 0, "value": 0.0})
    out = [HEADER]
    out.append("struct StopNode { bool leaf; int feature; double threshold; int left; int right; double value; };\n")
    out.append(f"constexpr bool kTrained = {'true' if model['trained'] else 'false'};\n")
    out.append(f"constexpr const char *kModelId = \"{model['id']}\";\n")
    out.append(f"constexpr double kDefaultThreshold = {model['threshold']!r};\n")
    out.append(f"constexpr double kBaseline = {model['baseline']!r};\n")
    out.append(f"constexpr int kTreeCount = {len(roots)};\n")
    out.append("constexpr int kTreeRoots[] = {" + ", ".join(str(r) for r in (roots or [0])) + "};\n")
    out.append("constexpr StopNode kNodes[] = {\n")
    for n in nodes:
        out.append(f"    {{{'true' if n['leaf'] else 'false'}, {n['feature']}, {float(n['threshold'])!r}, "
                   f"{n['left']}, {n['right']}, {float(n['value'])!r}}},\n")
    out.append("};\n")
    out.append(FOOTER)
    Path(path).write_text("".join(out))


def placeholder():
    return {"trained": False, "id": "untrained", "threshold": 0.0, "baseline": 0.0, "trees": [],
            "features": FEATURES}


def risk(model, x):
    raw = model["baseline"]
    for tree in model["trees"]:
        n = 0
        while not tree[n]["leaf"]:
            n = tree[n]["left"] if x[tree[n]["feature"]] <= tree[n]["threshold"] else tree[n]["right"]
        raw += tree[n]["value"]
    return 1.0 / (1.0 + math.exp(-raw))


def open_text(path):
    return gzip.open(path, "rt", newline="") if str(path).endswith(".gz") else open(path, newline="")


def load_traces(paths):
    """Decisions: key -> {seed, fresh, rows: [(checkpoint, features, leader)]} with a full schedule."""
    decisions = {}
    for path in paths:
        with open_text(path) as f:
            for row in csv.DictReader(f):
                key = (row["seed"], row["combat"], row["decision"])
                d = decisions.setdefault(key, {"seed": int(row["seed"]), "rows": []})
                d["rows"].append((int(row["checkpoint"]), [float(row[k]) for k in FEATURES], row["leader"]))
    complete = {}
    for key, d in decisions.items():
        d["rows"].sort(key=lambda r: r[0])
        if [r[0] for r in d["rows"]] != CHECKPOINTS:
            raise SystemExit(f"incomplete checkpoint schedule for decision {key}")
        d["final"] = d["rows"][-1][2]
        d["fresh"] = int(d["rows"][0][1][FEATURES.index("fresh_root")])
        complete[key] = d
    return complete


def export_hist_gbt(clf):
    trees = []
    for predictors in clf._predictors:
        nodes = predictors[0].nodes
        tree = []
        for n in nodes:
            leaf = bool(n["is_leaf"])
            tree.append({"leaf": leaf, "feature": int(n["feature_idx"]), "threshold": float(n["num_threshold"]),
                         "left": int(n["left"]), "right": int(n["right"]), "value": float(n["value"])})
        trees.append(tree)
    return float(clf._baseline_prediction.ravel()[0]), trees


def policy(decisions, model, threshold):
    """Learned policy: stop at the first checkpoint with risk < threshold or a strict lock."""
    used, errors, stops = [], [], 0
    for d in decisions:
        for ck, x, leader in d["rows"]:
            if ck == BMAX or x[FEATURES.index("lock")] > 0 or risk(model, x) < threshold:
                used.append(ck)
                errors.append(int(leader != d["final"]))
                stops += ck < BMAX
                break
    return used, errors, stops


def policy_199(decisions):
    used, errors = [], []
    for d in decisions:
        ck, x, leader = d["rows"][1]
        if not d["fresh"] and x[FEATURES.index("legal_actions")] > 1 and x[FEATURES.index("gap_share")] >= TOP_GAP_199:
            used.append(500)
            errors.append(int(leader != d["final"]))
        else:
            used.append(BMAX)
            errors.append(0)
    return used, errors


def summarize(decisions, used, errors):
    n = len(decisions)
    out = {"decisions": n, "saving": 1 - sum(used) / (BMAX * n) if n else 0.0,
           "disagreement": sum(errors) / n if n else 0.0}
    for name, flag in (("fresh", 1), ("retained", 0)):
        idx = [i for i, d in enumerate(decisions) if d["fresh"] == flag]
        out[name] = {"decisions": len(idx),
                     "saving": 1 - sum(used[i] for i in idx) / (BMAX * len(idx)) if idx else 0.0,
                     "disagreement": sum(errors[i] for i in idx) / len(idx) if idx else 0.0}
    return out


def train(args):
    from sklearn.ensemble import HistGradientBoostingClassifier
    lo, hi = (int(v) for v in args.train_seeds.split(":"))
    decisions = load_traces(args.trace)
    # One-action roots are committed without search in production.
    decisions = [d for d in decisions.values() if d["rows"][0][1][FEATURES.index("legal_actions")] > 1]
    train_set = [d for d in decisions if lo <= d["seed"] <= hi]
    X, y = [], []
    for d in train_set:
        for ck, x, leader in d["rows"][:-1]:
            X.append(x)
            y.append(int(leader != d["final"]))
    clf = HistGradientBoostingClassifier(max_iter=300, learning_rate=0.05, max_leaf_nodes=31, random_state=0)
    clf.fit(X, y)
    baseline, trees = export_hist_gbt(clf)
    digest = hashlib.sha256(json.dumps({"b": baseline, "t": trees}, sort_keys=True).encode()).hexdigest()[:12]
    model = {"trained": True, "id": f"gbt-{digest}", "threshold": args.threshold, "baseline": baseline,
             "trees": trees, "features": FEATURES, "train_seeds": [lo, hi], "rows": len(X)}
    # The exported trees must reproduce sklearn exactly.
    probe = clf.predict_proba(X[:2000])[:, 1]
    worst = max(abs(p - risk(model, x)) for p, x in zip(probe, X[:2000]))
    if worst > 1e-9:
        raise SystemExit(f"exported model differs from sklearn by {worst}")
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "model.json").write_text(json.dumps(model))
    write_cpp(out / "NativeSilverStopModel.cpp", model)
    report = {"model_id": model["id"], "train_seeds": [lo, hi], "train_rows": len(X)}
    for name, subset in (("train", train_set), ("other", [d for d in decisions if not lo <= d["seed"] <= hi])):
        report[name] = {"rule_199": summarize(subset, *policy_199(subset))}
        for thr in sorted({args.threshold, 0.005, 0.01, 0.02, 0.05}):
            used, errors, stops = policy(subset, model, thr)
            report[name][f"learned_{thr}"] = dict(summarize(subset, used, errors), stops=stops)
    (out / "offline.json").write_text(json.dumps(report, indent=1))
    print(json.dumps(report, indent=1))


def selftest():
    # Hand-built model: one stump on rho.
    model = {"trained": True, "id": "t", "threshold": 0.5, "baseline": 0.0,
             "trees": [[{"leaf": False, "feature": FEATURES.index("rho"), "threshold": 0.5, "left": 1, "right": 2, "value": 0},
                        {"leaf": True, "feature": 0, "threshold": 0, "left": 0, "right": 0, "value": 2.0},
                        {"leaf": True, "feature": 0, "threshold": 0, "left": 0, "right": 0, "value": -2.0}]]}
    x = [0.0] * len(FEATURES)
    assert risk(model, x) > 0.8
    x[FEATURES.index("rho")] = 0.9
    assert risk(model, x) < 0.2
    rows = [(ck, list(x), "a") for ck in CHECKPOINTS]
    d = {"seed": 1, "fresh": 1, "final": "a", "rows": rows}
    used, errors, stops = policy([d], model, 0.5)
    assert used == [250] and errors == [0] and stops == 1
    used, errors = policy_199([d])
    assert used == [BMAX]
    print("selftest ok")


def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    ph = sub.add_parser("placeholder")
    ph.add_argument("--cpp", required=True)
    tr = sub.add_parser("train")
    tr.add_argument("trace", nargs="+")
    tr.add_argument("--train-seeds", required=True)
    tr.add_argument("--threshold", type=float, default=0.01)
    tr.add_argument("--out-dir", required=True)
    sub.add_parser("selftest")
    args = p.parse_args()
    if args.cmd == "placeholder":
        write_cpp(args.cpp, placeholder())
    elif args.cmd == "train":
        train(args)
    else:
        selftest()


if __name__ == "__main__":
    sys.exit(main())
