#!/usr/bin/env python3
"""Analyze multi-checkpoint Silver continuation diagnostics.

The input is one row per decision/checkpoint from the opt-in
STS_COMBAT_SEQUENTIAL_DIAG_FILE stream.  This tool deliberately keeps the
controller offline: predictions are made on trajectories generated by the
full 10,000-simulation reference search, and no action is executed here.
"""

