#!/usr/bin/env bash
# usage: run_one.sh SILVER_SIMS OOC_SIMS SEED OUTDIR
set -euo pipefail
S=$1; O=$2; SEED=$3; OUT=$4
REPO=/home/user/sts_ai
OUT=$(realpath -m "$OUT"); mkdir -p "$OUT"
cd "$REPO"
tag="s${S}_o${O}_seed${SEED}"
env -i HOME=$HOME PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \
  OMP_NUM_THREADS=${THREADS:-4} STS_EXECUTABLE_GIT_SHA=$(git rev-parse HEAD) \
  STS_COLLECT_KEYS=0 STS_FAIR=1 STS_NATIVE_OOC=1 STS_STOP_AFTER_ACT=3 \
  STS_OOC_MCTS=1 STS_OOC_MCTS_SIMS=$O STS_OOC_MCTS_ALLOW_SILVER_BUDGET_MISMATCH=${MISMATCH:-1} \
  STS_OOC_MCTS_CPUCT=1.5 STS_OOC_MCTS_EARLY_STOP=1 STS_OOC_MCTS_GAP_STOP_20=0 \
  STS_OOC_MCTS_LEAF_COMBATS=0 STS_OOC_MCTS_LEAF_POLICY=v4 STS_OOC_MCTS_LEAF_VALUE=native \
  STS_OOC_MCTS_MAX_DEPTH=32 STS_OOC_MCTS_PRIOR=policy STS_OOC_MCTS_ROOT_SELECTION=visits \
  STS_OOC_MCTS_TEMPERATURE=1 STS_OOC_MCTS_WIDEN_ALPHA=0.5 STS_OOC_MCTS_WIDEN_K=2 \
  STS_OOC_STRATEGIC_BOSS_RELIC=1 STS_OOC_STRATEGIC_EVENT=1 STS_OOC_STRATEGIC_MARGIN=1.0 \
  STS_OOC_STRATEGIC_REST=1 STS_OOC_STRATEGIC_SHOP=1 STS_OOC_STRATEGIC_TREASURE=1 \
  STS_OOC_STRATEGIC_TOK_NN=$REPO/selfplay/models/ooc_strategic_tok_final.native \
  STS_SILVER_ADAPTIVE=0 STS_SILVER_EXACT_ROOT_BUDGETS=1 STS_SILVER_REUSE_CAP_MODE=allocated \
  STS_SILVER_SEARCH=1 STS_SILVER_TELEMETRY=0 STS_SILVER_VNET_LEAF_DIRECT=0 \
  bash tools/seed_guard.sh ${BIN:-build/grid-release/one_combat} bestbench "$S" 1 0 "$SEED" "$OUT/$tag.csv" \
  > "$OUT/$tag.log" 2>&1
echo "$tag rc=$?"
